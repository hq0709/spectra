#!/usr/bin/env bash
# Regenerate the lock files from environment-core.yml / environment-gpu.yml.
#
#   container/relock.sh core   # conda-lock.yml + conda-linux-64.lock
#   container/relock.sh gpu    # conda-lock-gpu.yml + conda-gpu-linux-64.lock
#                              # + requirements-gpu.lock.txt
#   container/relock.sh all
#
# Tools come from the `spectra-tools` env (conda-lock, uv); override with
# TOOLS=/path/to/env. Solver backend: CONDA (default: the development cluster base conda).
#
# Why the GPU lock has two halves: conda-lock 4.0.3 resolves the pip layer but
# then cannot choose wheels tagged manylinux_2_27 (its MANYLINUX_TAGS list
# skips that tag), which is how NVIDIA ships the CUDA 12.9 libraries
# ("Unable to find installation candidates for nvidia-cublas-cu12
# (12.9.1.4)"). So conda-lock locks the conda layer, that layer is installed
# into a throwaway prefix, and `uv pip compile --generate-hashes` locks the pip
# layer against exactly those installed packages.

set -euo pipefail
ulimit -u 65536 2>/dev/null || true

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS="${TOOLS:-/path/to/home/myconda/envs/spectra-tools}"
CONDA="${CONDA:-/path/to/home/myconda/bin/conda}"
BUILD="$HERE/.build"
WHAT="${1:-all}"

# Small thread pools: uv/rayon/tokio and BLAS default to one thread per core.
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 RAYON_NUM_THREADS=2
export UV_CONCURRENT_DOWNLOADS=4 UV_CONCURRENT_BUILDS=1 UV_CONCURRENT_INSTALLS=2
export UV_NO_CONFIG=1 UV_CACHE_DIR="${UV_CACHE_DIR:-$BUILD/uv-cache}"
CPUSET="taskset -c 0-3"
command -v taskset >/dev/null || CPUSET=""

cd "$HERE"
mkdir -p "$BUILD"

lock_conda() {  # $1 = source yml, $2 = unified lock, $3 = explicit lock name template
  rm -f "$2"
  $CPUSET "$TOOLS/bin/conda-lock" lock --conda "$CONDA" --no-mamba --no-micromamba \
      -f "$1" -p linux-64 --virtual-package-spec virtual-packages.yml --lockfile "$2"
  "$TOOLS/bin/conda-lock" render -k explicit -p linux-64 --filename-template "$3" "$2"
}

relock_core() {
  lock_conda environment-core.yml conda-lock.yml 'conda-{platform}.lock'
}

relock_gpu() {
  local layer=".build/environment-gpu.conda-layer.yml" prefix="$BUILD/gpu-conda-layer"
  # 1. conda layer: environment-gpu.yml without its pip block.
  "$TOOLS/bin/python" -I - environment-gpu.yml "$layer" "$BUILD/requirements-gpu.in" <<'EOF'
import sys, yaml
src, layer_out, pip_out = sys.argv[1:4]
env = yaml.safe_load(open(src))
deps, pip = [], []
for d in env["dependencies"]:
    if isinstance(d, dict) and "pip" in d:
        pip = d["pip"]
    else:
        deps.append(d)
layer = {"name": env["name"], "channels": env["channels"], "dependencies": deps}
with open(layer_out, "w") as f:
    f.write("# GENERATED by relock.sh from environment-gpu.yml (conda layer only)\n")
    yaml.safe_dump(layer, f, sort_keys=False)
with open(pip_out, "w") as f:
    f.write("# GENERATED by relock.sh from the pip block of environment-gpu.yml\n")
    f.write("\n".join(pip) + "\n")
EOF
  lock_conda "$layer" conda-lock-gpu.yml 'conda-gpu-{platform}.lock'

  # 2. install that layer so the pip resolve sees the real installed versions.
  rm -rf "$prefix"
  $CPUSET "$CONDA" create -y -q -p "$prefix" --file conda-gpu-linux-64.lock >/dev/null
  "$prefix/bin/python" -I -m pip list --format=freeze | sort -f > "$BUILD/constraints-conda-gpu.txt"

  # 3. pip layer. llguidance comes from conda-forge (PyPI only has
  #    manylinux_2_31 wheels for 1.7.x); the never-true marker drops it from
  #    uv's graph and `pip check` in the built env re-checks vllm's range.
  printf '%s\n' "llguidance ; python_version < '0'" > "$BUILD/overrides-conda.txt"
  $CPUSET "$TOOLS/bin/uv" pip compile "$BUILD/requirements-gpu.in" \
      -c "$BUILD/constraints-conda-gpu.txt" --override "$BUILD/overrides-conda.txt" \
      --python-version 3.11.17 --python-platform x86_64-manylinux_2_28 \
      --torch-backend cu129 --no-build --generate-hashes --emit-index-url \
      --custom-compile-command "container/relock.sh gpu" \
      -o "$BUILD/requirements-gpu.uv.txt"

  # 4. drop what the conda layer already provides, so pip installs nothing
  #    over a conda package.
  "$TOOLS/bin/python" -I - "$BUILD/requirements-gpu.uv.txt" "$BUILD/constraints-conda-gpu.txt" \
      requirements-gpu.lock.txt <<'EOF'
import re, sys
uv_out, conda_freeze, dst = sys.argv[1:4]
norm = lambda s: re.sub(r"[-_.]+", "-", s).lower()
conda = {norm(l.split("==")[0]) for l in open(conda_freeze) if "==" in l}
blocks, cur = [], []
for line in open(uv_out):
    if line[:1].isalnum() or line.startswith("--"):
        if cur: blocks.append(cur)
        cur = [line]
    else:
        cur.append(line)
if cur: blocks.append(cur)
kept, dropped = [], []
for b in blocks:
    m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*)\s*(==| @ )", b[0])
    if m and norm(m.group(1)) in conda:
        dropped.append(m.group(1)); continue
    kept.append("".join(b))
# uv resolves torch/torchvision/torchaudio/torchcodec from the cu129 index via
# --torch-backend but emits only the PyPI index; pip needs both.
extra = "--extra-index-url https://download.pytorch.org/whl/cu129\n"
if extra not in kept:
    at = next(i for i, b in enumerate(kept) if b.startswith("--index-url"))
    kept.insert(at + 1, extra)
with open(dst, "w") as f:
    f.write("# pip layer of environment-gpu.yml for linux-64 / glibc>=2.28 / CUDA 12.9.\n")
    f.write("# GENERATED by container/relock.sh gpu (uv pip compile against the\n")
    f.write("# installed conda layer conda-gpu-linux-64.lock). Install with:\n")
    f.write("#   python -m pip install --no-deps --require-hashes -r requirements-gpu.lock.txt\n")
    f.write("# Provided by the conda layer, so not listed here: " + ", ".join(sorted(dropped)) + "\n")
    f.write("".join(kept))
print(f"pip layer: {sum(1 for b in kept if b[:1].isalnum())} packages; conda-provided, removed: {len(dropped)}")
EOF
  rm -rf "$prefix"
}

case "$WHAT" in
  core) relock_core ;;
  gpu)  relock_gpu ;;
  all)  relock_core; relock_gpu ;;
  *) echo "usage: $0 core|gpu|all" >&2; exit 2 ;;
esac
